// Writes includes/Admin/Icons.php: the lucide icons the admin page uses (the dashboard's icon set),
// inlined as SVG so the page loads nothing more. Usage: node bin/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const names = [
  'arrow-right', 'arrow-up-right', 'check', 'circle-check', 'circle-alert', 'triangle-alert', 'info', 'x',
  'refresh-cw', 'shield-check', 'mouse-pointer-click', 'globe', 'search', 'settings', 'link-2', 'zap',
  'play', 'list', 'layout-dashboard', 'lock', 'shuffle', 'bot', 'message-circle', 'corner-down-right',
  'chevron-right', 'unplug', 'clock', 'key-round', 'plug', 'monitor', 'chart-column', 'gauge', 'copy',
  'external-link', 'server', 'route', 'import', 'download', 'package',
];
const icons = {};
for (const name of names) {
  const svg = readFileSync(join(root, 'node_modules/lucide-static/icons', `${name}.svg`), 'utf8');
  icons[name] = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s+/g, ' ').trim();
}
const php = `<?php
/**
 * The lucide icons of the admin page (ISC license), generated by bin/build-icons.mjs.
 *
 * @package RedirHub\\Redirects
 */

namespace RedirHub\\Redirects\\Admin;

defined( 'ABSPATH' ) || exit;

/**
 * Inline SVG icons, the same set as the RedirHub dashboard.
 */
final class Icons {

	/** The inner markup of each icon, by name. */
	const PATHS = ${'array(\n' + Object.entries(icons).map(([k, v]) => `\t\t'${k}' => '${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`).join('\n') + '\n\t)'};

	/**
	 * An icon as an inline SVG, hidden from screen readers.
	 *
	 * @param string $name  An icon of PATHS.
	 * @param string $class Classes of the svg.
	 */
	public static function svg( string $name, string $class = 'rh:size-4' ): string {
		$paths = self::PATHS[ $name ] ?? '';

		return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="' . esc_attr( $class ) . '" aria-hidden="true" focusable="false">' . $paths . '</svg>';
	}
}
`;
writeFileSync(join(root, 'includes/Admin/Icons.php'), php);
console.log(`${names.length} icons written`);
